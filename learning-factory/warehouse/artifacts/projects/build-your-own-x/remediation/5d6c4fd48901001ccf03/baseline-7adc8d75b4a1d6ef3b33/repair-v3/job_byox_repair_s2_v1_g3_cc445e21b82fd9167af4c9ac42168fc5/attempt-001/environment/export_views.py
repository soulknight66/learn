#!/usr/bin/env python3
"""Create and verify separated learner and instructor directory artifacts."""

from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path
import shutil
import stat
import sys
from typing import Iterable


ROOT = Path(__file__).resolve().parents[1]
MANIFEST_PATH = Path("environment/VIEW_MANIFEST.json")
PROJECT_ID = "project_884ee11fc61abc48b60825556299dae5"

LEARNER_TOP_LEVEL = (
    "AGENTS.md",
    "CONCEPTS.md",
    "DESIGN_QUESTIONS.md",
    "MANIFEST.yaml",
    "README.md",
    "REQUIREMENTS.md",
    "environment",
    "public_tests",
    "starter",
)
INSTRUCTOR_TOP_LEVEL = (
    "AGENTS.md",
    "CONCEPTS.md",
    "DESIGN_QUESTIONS.md",
    "LICENSE_BOUNDARY.md",
    "MANIFEST.yaml",
    "PROVENANCE.json",
    "README.md",
    "REQUIREMENTS.md",
    "VALIDATION.md",
    "adversarial",
    "benchmarks",
    "debugging",
    "environment",
    "public_tests",
    "review_exercises",
    "sealed",
    "starter",
)
ROLE_TOP_LEVEL = {
    "instructor": INSTRUCTOR_TOP_LEVEL,
    "learner": LEARNER_TOP_LEVEL,
}


class ExportError(Exception):
    """A deterministic export or verification failure."""


def _sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as stream:
        for block in iter(lambda: stream.read(1024 * 1024), b""):
            digest.update(block)
    return digest.hexdigest()


def _regular_files(root: Path) -> list[Path]:
    files: list[Path] = []
    for path in sorted(root.rglob("*")):
        mode = path.lstat().st_mode
        relative = path.relative_to(root)
        if path.is_symlink() or not (stat.S_ISDIR(mode) or stat.S_ISREG(mode)):
            raise ExportError(f"non-regular export entry: {relative.as_posix()}")
        if stat.S_ISREG(mode):
            files.append(relative)
    return files


def _copy_entry(source: Path, destination: Path) -> None:
    if source.name == "__pycache__" or source.suffix in {".pyc", ".pyo"}:
        raise ExportError(f"generated bytecode is not exportable: {source}")
    mode = source.lstat().st_mode
    if source.is_symlink() or not (stat.S_ISDIR(mode) or stat.S_ISREG(mode)):
        raise ExportError(f"source entry is not a regular file or directory: {source}")
    if stat.S_ISREG(mode):
        destination.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(source, destination)
        return
    destination.mkdir(parents=True, exist_ok=True)
    for child in sorted(source.iterdir(), key=lambda item: item.name):
        _copy_entry(child, destination / child.name)


def _manifest_document(view: Path, role: str) -> dict[str, object]:
    files = []
    for relative in _regular_files(view):
        if relative == MANIFEST_PATH:
            continue
        path = view / relative
        files.append(
            {
                "path": relative.as_posix(),
                "sha256": _sha256(path),
                "size": path.stat().st_size,
            }
        )
    included = ROLE_TOP_LEVEL[role]
    return {
        "directories": [
            path.relative_to(view).as_posix()
            for path in sorted(view.rglob("*"))
            if path.is_dir()
        ],
        "excluded_top_level": sorted(set(INSTRUCTOR_TOP_LEVEL) - set(included)),
        "files": files,
        "included_top_level": list(included),
        "project_id": PROJECT_ID,
        "role": role,
        "schema_version": 1,
    }


def verify_view(view: Path, expected_role: str | None = None) -> dict[str, object]:
    view = view.resolve()
    manifest_path = view / MANIFEST_PATH
    try:
        raw = manifest_path.read_text(encoding="utf-8")
        manifest = json.loads(raw)
    except (OSError, UnicodeDecodeError, json.JSONDecodeError) as exc:
        raise ExportError(f"view manifest is unreadable: {exc}") from exc
    if not isinstance(manifest, dict):
        raise ExportError("view manifest must be a JSON object")
    role = manifest.get("role")
    if role not in ROLE_TOP_LEVEL:
        raise ExportError("view manifest has an unknown role")
    if expected_role is not None and role != expected_role:
        raise ExportError(f"expected {expected_role} view, found {role}")
    canonical = _manifest_document(view, role)
    if manifest != canonical:
        raise ExportError("view files, hashes, sizes, or disclosure policy differ from manifest")
    actual_top = tuple(sorted(path.name for path in view.iterdir()))
    expected_top = tuple(sorted(ROLE_TOP_LEVEL[role]))
    if actual_top != expected_top:
        raise ExportError("view has an unexpected top-level entry")
    return {
        "files": len(canonical["files"]),
        "manifest_sha256": hashlib.sha256(raw.encode("utf-8")).hexdigest(),
        "role": role,
    }


def create_views(destination: Path) -> list[dict[str, object]]:
    destination = destination.resolve()
    if destination.exists() or destination.is_symlink():
        raise ExportError("destination must not already exist")
    for name in INSTRUCTOR_TOP_LEVEL:
        source = ROOT / name
        if not source.exists() or source.is_symlink():
            raise ExportError(f"canonical source entry is missing or unsafe: {name}")
        try:
            destination.relative_to(source.resolve())
        except ValueError:
            pass
        else:
            raise ExportError(f"destination must not be inside canonical source entry: {name}")

    destination.mkdir(parents=True)
    summaries = []
    for role in ("learner", "instructor"):
        view = destination / role
        view.mkdir()
        for name in ROLE_TOP_LEVEL[role]:
            _copy_entry(ROOT / name, view / name)
        manifest = _manifest_document(view, role)
        manifest_path = view / MANIFEST_PATH
        manifest_path.parent.mkdir(parents=True, exist_ok=True)
        manifest_path.write_text(
            json.dumps(manifest, indent=2, sort_keys=True) + "\n",
            encoding="utf-8",
        )
        summaries.append(verify_view(view, role))
    return summaries


def _print_summaries(summaries: Iterable[dict[str, object]]) -> None:
    for summary in summaries:
        print(json.dumps(summary, sort_keys=True))


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    subparsers = parser.add_subparsers(dest="command", required=True)
    create = subparsers.add_parser("create", help="create learner/ and instructor/ views")
    create.add_argument("destination", type=Path)
    verify = subparsers.add_parser("verify", help="verify one previously exported view")
    verify.add_argument("view", type=Path)
    verify.add_argument("--role", choices=sorted(ROLE_TOP_LEVEL))
    args = parser.parse_args(argv)
    try:
        if args.command == "create":
            _print_summaries(create_views(args.destination))
        else:
            _print_summaries([verify_view(args.view, args.role)])
    except ExportError as exc:
        print(f"export error: {exc}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
